-- Choosing where the library opens when its top folder has no folders: the
-- clearer message and the Top folder button, which changes KOReader's home folder.
local H = ...
local Actions = require("solarui/actions")
local Library = require("solarui/data/library")
local UIManager = require("ui/uimanager")
local out = os.getenv("SOLARUI_DRIVE_OUT")
H.step(2, function()
    os.execute("mkdir -p '" .. out .. "/flat' '" .. out .. "/shelf/Fiction'")
    G_reader_settings:saveSetting("home_dir", out .. "/flat")
    Library.reset()
    H.app().open("settings"); Actions.pickLibraryStart()
end)
H.step(1.5, function()
    UIManager:forceRePaint(); H.shot("t1-empty")
    H.check(H.find("Top folder") ~= nil, "the picker offers Top folder")
    H.tap("Top folder")
end)
H.step(1.5, function()
    UIManager:forceRePaint(); H.shot("t2-pathchooser")
    -- (choosing a folder in KOReader's chooser calls this)
    local top
    for _i, w in ipairs(UIManager._window_stack) do if w.widget.onConfirm then top = w.widget end end
    H.check(top ~= nil, "KOReader's folder chooser opens")
    top.onConfirm(out .. "/shelf")
    UIManager:close(top)
end)
H.step(1.5, function()
    UIManager:forceRePaint(); H.shot("t3-done")
    H.check(Library.home():find("/shelf$") ~= nil, "the library's top folder changed: " .. Library.home())
    Actions.pickLibraryStart()
end)
H.step(1.5, function()
    UIManager:forceRePaint(); H.shot("t4-picker-now")
    H.check(H.find("Fiction") ~= nil, "the picker now lists the new top's folders")
end)
