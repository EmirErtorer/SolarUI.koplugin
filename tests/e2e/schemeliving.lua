-- Plants and animals and the colour scheme, in Peacock dark: their own colours
-- (the default), the scheme everywhere, home only, home with the companion
-- kept, and Yüzsüz always herself.
local H = ...
local dir = os.getenv("SOLARUI_DRIVE_SCRIPT"):match("^(.*)/[^/]+$")
local K = dofile(dir .. "/gardenkit.lua")(H)
local Settings = require("solarui/settings")
local Theme = require("solarui/theme")
local Natural = require("solarui/art/natural")
local Pet = require("solarui/garden/pet")
local State = require("solarui/garden/state")
H.step(2, function()
    K.reset({ season = "summer", hour = 11 })
    K.everyone()
    K.settle()
    State.get().pet = nil
    Pet.adopt("robin")
    Settings.set("scheme", "peacock")
    Theme.set("mode", "dark")
    H.check(Natural.mode() == "off", "plants and animals keep their own colours by default")
    H.check(Natural.is("plant_rose") and Natural.is("dock_lily") and Natural.is("home:animal_robin"), "with it off, every living thing is natural")
    H.app().open("home")
end)
local function both(tag)
    H.step(1.5, function() H.app().go("home"); H.app().render("full") end)
    H.step(2, function() require("ui/uimanager"):forceRePaint(); H.shot(tag .. "-home"); H.app().push("garden") end)
    H.step(2.5, function() require("ui/uimanager"):forceRePaint(); H.shot(tag .. "-garden") end)
end
both("a-own")
H.step(.5, function()
    Theme.set("scheme_living", "all")
    H.check(not Natural.is("plant_rose") and not Natural.is("goal_tree") and not Natural.is("home:animal_robin"), "everywhere: the garden, the pages and the companion take the scheme")
    H.check(Natural.is("animal_yuzsuz") and Natural.is("home:animal_yuzsuz"), "Yüzsüz keeps her colours everywhere")
end)
both("b-all")
H.step(.5, function()
    Theme.set("scheme_living", "home")
    H.check(not Natural.is("dock_lily") and not Natural.is("rose_cluster") and not Natural.is("home:plant_rose"), "home only: home's living things and the companion take the scheme")
    H.check(Natural.is("plant_rose") and Natural.is("goal_tree") and Natural.is("garden_tuft"), "home only: the garden and other pages keep their own colours")
end)
both("c-home")
H.step(.5, function()
    Theme.set("scheme_companion_kept", true)
    H.check(Natural.is("home:animal_robin") and not Natural.is("dock_lily"), "the companion can keep their own colours while home takes the scheme")
end)
both("d-home-kept")
H.step(.5, function()
    Theme.set("scheme_companion_kept", false)
    State.get().pet = nil
    Pet.adopt("yuzsuz")
    H.check(Natural.is("home:animal_yuzsuz"), "Yüzsüz on home keeps her colours too")
end)
H.step(1.5, function() H.app().go("home"); H.app().render("full") end)
H.step(2, function() require("ui/uimanager"):forceRePaint(); H.shot("e-yuzsuz-home") end)
H.step(.5, function() H.app().go("settings") end)
H.step(2, function() require("ui/uimanager"):forceRePaint(); H.shot("f-settings"); Theme.set("scheme_living", "off"); Theme.set("mode", "light"); Settings.set("scheme", "garden") end)
